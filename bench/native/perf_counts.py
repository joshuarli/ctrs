"""Strict per-API-thread perf stat coverage and per-success normalization."""
import json
import math
import re

from counter_specs import SYSCALLS, selectors, VERSION


def events(tag):
    if not re.fullmatch(r'np[0-9a-f]{12}', tag):
        raise ValueError('invalid owned trace group')
    return ('task-clock', 'context-switches', 'cpu-migrations',
            *(tag + ':enter_' + name for name in SYSCALLS), 'sched:sched_waking')


def summarize(text, *, tag, required_tids, successful_operations):
    errors, values = [], {}
    expected = {(tag + '-' + str(tid), event) for tid in required_tids for event in events(tag)}
    if not required_tids or type(successful_operations) is not int or successful_operations <= 0:
        errors.append('missing required threads or successful operation count')
    for index, line in enumerate(text.splitlines(), 1):
        if not line.strip():
            continue
        try:
            row = json.loads(line)
            key = row['thread'], row['event']
            if key not in expected or key in values:
                raise ValueError('unexpected or duplicate thread/event')
            value = float(row['counter-value'])
            runtime, coverage = float(row['event-runtime']), float(row['pcnt-running'])
            if not all(math.isfinite(n) for n in (value, runtime, coverage)) or value < 0 or runtime <= 0 or abs(coverage - 100) > .01:
                raise ValueError('counter invalid or not fully scheduled')
            if row['unit'] != ('msec' if key[1] == 'task-clock' else ''):
                raise ValueError('unexpected counter unit')
            if key[1] != 'task-clock' and value != int(value):
                raise ValueError('nonintegral event count')
            values[key] = value
        except (KeyError, ValueError, TypeError) as exc:
            errors.append(f'row {index}: {exc}')
    missing = expected - values.keys()
    if missing:
        errors.append('missing required thread/events: ' + repr(sorted(missing)))
    totals = {event: sum(values[(tag + '-' + str(tid), event)] for tid in required_tids)
              for event in events(tag)} if not errors else None
    return {'status': 'unknown' if errors else 'ok', 'errors': errors,
        'required_threads': list(required_tids), 'required_cells': len(expected), 'observed_cells': len(values),
        'method': 'perf stat per-thread, no inherit; matched ARM64 syscall-entry kprobes; scheduler event in API waker context',
        'counter_units': {event: 'milliseconds' if event == 'task-clock' else 'events' for event in events(tag)},
        'counts': totals, 'successful_operations': successful_operations,
        'per_successful_operation': {event: value / successful_operations for event, value in totals.items()} if totals else None,
        'application_cpu_seconds': totals['task-clock'] / 1000 if totals else None,
        'application_cpu_seconds_per_success': totals['task-clock'] / 1000 / successful_operations if totals else None,
        'scope': 'only required API threads; sched_waking counts wakes generated by API threads, not off-CPU target wait/wake latency'}


def summarize_detail(text, *, tag, required_tids, successful_operations):
    """Read one complete thread block per pinned perf selector, in command order."""
    spec = selectors(tag)
    tids = {str(tid) for tid in required_tids}
    errors, totals = [], {}
    try:
        if not tids or type(successful_operations) is not int or successful_operations <= 0:
            raise ValueError('missing required threads or successful operations')
        rows = [json.loads(line) for line in text.splitlines() if line.strip()]
        if len(rows) != len(tids) * len(spec):
            raise ValueError('required selector/thread cell count differs')
        for index, selector in enumerate(spec):
            block = rows[index * len(tids):(index + 1) * len(tids)]
            expected = {tag + '-' + tid for tid in tids}
            seen = set()
            total = 0
            for row in block:
                if row['event'] != selector['event'] or row['thread'] not in expected or row['thread'] in seen:
                    raise ValueError('selector order or thread coverage differs')
                seen.add(row['thread'])
                value, runtime, coverage = (float(row[key]) for key in ('counter-value', 'event-runtime', 'pcnt-running'))
                if not all(math.isfinite(n) for n in (value, runtime, coverage)) or value < 0 or runtime <= 0 or abs(coverage - 100) > .01:
                    raise ValueError('counter invalid or not fully scheduled')
                clock = selector['label'] == 'task-clock'
                if row['unit'] != ('msec' if clock else '') or (not clock and value != int(value)):
                    raise ValueError('counter unit/value differs')
                total += value
            totals[selector['label']] = total
        totals['futex_other_commands'] = totals['futex_all'] - sum(totals[key] for key in ('futex_wait', 'futex_wake', 'futex_wait_bitset'))
        totals['futex_other_negative_returns'] = totals['futex_returns'] - sum(totals[key] for key in ('futex_eagain', 'futex_timeout', 'futex_zero', 'futex_positive'))
        if min(totals['futex_other_commands'], totals['futex_other_negative_returns']) < 0:
            raise ValueError('filtered counters do not form a valid classification')
    except (KeyError, ValueError, TypeError) as exc:
        errors.append(str(exc))
        totals = None
    return {'fixture_version': VERSION, 'status': 'unknown' if errors else 'ok', 'errors': errors,
        'method': 'pinned perf ordered per-thread selector blocks; native known-count C conformance',
        'selectors': spec, 'required_threads': sorted(tids), 'required_cells': len(tids) * len(spec),
        'counts': totals, 'successful_operations': successful_operations,
        'counter_units': {label: 'milliseconds' if label == 'task-clock' else 'events'
                          for label in ([selector['label'] for selector in spec] + ['futex_other_commands', 'futex_other_negative_returns'])},
        'per_successful_operation': {label: value / successful_operations for label, value in totals.items()} if totals else None,
        'application_cpu_seconds': totals['task-clock'] / 1000 if totals else None,
        'application_cpu_seconds_per_success': totals['task-clock'] / 1000 / successful_operations if totals else None,
        'inflight_futex_edge_bound_per_boundary': len(tids),
        'edge_scope': 'bound covers concurrent calls crossing each boundary; selector activation skew is separate; zero missed probes is required independently',
        'scope': 'required API threads only; futex counts/returns are not per-call CPU or blocked/wake latency'}
