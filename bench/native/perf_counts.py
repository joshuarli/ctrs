"""Strict per-API-thread perf stat coverage and per-success normalization."""
import json
import math
import re

SYSCALLS = ('futex', 'read', 'write', 'epoll_pwait', 'recvfrom', 'sendto')


def events(tag):
    if not re.fullmatch(r'np[0-9a-f]{12}', tag):
        raise ValueError('invalid owned trace group')
    return ('task-clock', 'context-switches', 'cpu-migrations',
            *(tag + ':enter_' + name for name in SYSCALLS), 'sched:sched_waking')


def summarize(text, *, tag, required_tids, successful_operations):
    errors, values = [], {}
    expected = {(tag + '-' + str(tid), event) for tid in required_tids for event in events(tag)}
    if not required_tids or type(successful_operations) is not int or successful_operations <= 0:
        errors.append('missing required threads or successful operation count')
    for index, line in enumerate(text.splitlines(), 1):
        if not line.strip():
            continue
        try:
            row = json.loads(line)
            key = row['thread'], row['event']
            if key not in expected or key in values:
                raise ValueError('unexpected or duplicate thread/event')
            value = float(row['counter-value'])
            runtime, coverage = float(row['event-runtime']), float(row['pcnt-running'])
            if not all(math.isfinite(n) for n in (value, runtime, coverage)) or value < 0 or runtime <= 0 or abs(coverage - 100) > .01:
                raise ValueError('counter invalid or not fully scheduled')
            if row['unit'] != ('msec' if key[1] == 'task-clock' else ''):
                raise ValueError('unexpected counter unit')
            if key[1] != 'task-clock' and value != int(value):
                raise ValueError('nonintegral event count')
            values[key] = value
        except (KeyError, ValueError, TypeError) as exc:
            errors.append(f'row {index}: {exc}')
    missing = expected - values.keys()
    if missing:
        errors.append('missing required thread/events: ' + repr(sorted(missing)))
    totals = {event: sum(values[(tag + '-' + str(tid), event)] for tid in required_tids)
              for event in events(tag)} if not errors else None
    return {'status': 'unknown' if errors else 'ok', 'errors': errors,
        'required_threads': list(required_tids), 'required_cells': len(expected), 'observed_cells': len(values),
        'method': 'perf stat per-thread, no inherit; matched ARM64 syscall-entry kprobes; scheduler event in API waker context',
        'counter_units': {event: 'milliseconds' if event == 'task-clock' else 'events' for event in events(tag)},
        'counts': totals, 'successful_operations': successful_operations,
        'per_successful_operation': {event: value / successful_operations for event, value in totals.items()} if totals else None,
        'application_cpu_seconds': totals['task-clock'] / 1000 if totals else None,
        'application_cpu_seconds_per_success': totals['task-clock'] / 1000 / successful_operations if totals else None,
        'scope': 'only required API threads; sched_waking counts wakes generated by API threads, not off-CPU target wait/wake latency'}
